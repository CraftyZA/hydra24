#!/bin/bash
set -euo pipefail

# Deploys hydra24.co.za: builds the backend (Quarkus native, in a container),
# applies this project's Terraform (iac/), writes the site's auth config from
# its outputs, uploads ui/ to S3 and invalidates CloudFront.
#   --skip-build  reuse backend/target/function.zip from the last build
cd "$(dirname "$0")"

IAC_DIR="iac"
UI_DIR="ui"
BACKEND_DIR="backend"
AUTH_CONFIG_FILE="$UI_DIR/common/auth-config.js"

SKIP_BUILD=false
[[ "${1:-}" == "--skip-build" ]] && SKIP_BUILD=true

# Step 1: Backend. Tests run first; the native build takes a few minutes.
if [ "$SKIP_BUILD" = false ]; then
    echo "Step 1/4: Building backend..."
    mvn -q -f "$BACKEND_DIR/pom.xml" clean package
    (cd "$BACKEND_DIR/target" && cp function-runner bootstrap && zip -q function.zip bootstrap)
else
    echo "Step 1/4: Skipping backend build (--skip-build)"
fi

# Step 2: Terraform. This project has its own state, so a full apply only ever
# touches hydra24 resources.
echo ""
echo "Step 2/4: Applying hydra24 infrastructure..."
terraform -chdir="$IAC_DIR" init -input=false > /dev/null
terraform -chdir="$IAC_DIR" apply -input=false

S3_BUCKET=$(terraform -chdir="$IAC_DIR" output -raw hydra24_site_bucket)
CLOUDFRONT_DIST_ID=$(terraform -chdir="$IAC_DIR" output -raw hydra24_site_distribution_id)

# Step 3: Site auth config. Public values (no secrets), so it is fine in the browser.
echo ""
echo "Step 3/4: Writing $AUTH_CONFIG_FILE..."
cat > "$AUTH_CONFIG_FILE" <<EOF
// Generated by deploy.sh from Terraform outputs. Do not edit or commit.
const AUTH_CONFIG = {
    authUrl: '$(terraform -chdir="$IAC_DIR" output -raw auth_url)',
    clientId: '$(terraform -chdir="$IAC_DIR" output -raw auth_client_id)',
    apiUrl: '$(terraform -chdir="$IAC_DIR" output -raw api_url)'
};
EOF

# Step 4: Upload. HTML/CSS/JS revalidate every load; images get a day.
echo ""
echo "Step 4/4: Uploading $UI_DIR to s3://$S3_BUCKET/ ..."
aws s3 sync "$UI_DIR/" "s3://$S3_BUCKET/" \
    --exclude="*" --include="*.html" --include="*.css" --include="*.js" \
    --cache-control "no-cache" --delete --only-show-errors
aws s3 sync "$UI_DIR/" "s3://$S3_BUCKET/" \
    --exclude="*" --include="*.jpg" --include="*.jpeg" --include="*.png" --include="*.ico" \
    --cache-control "public, max-age=86400" --delete --only-show-errors

INVALIDATION_ID=$(aws cloudfront create-invalidation --distribution-id "$CLOUDFRONT_DIST_ID" \
    --paths "/*" --query 'Invalidation.Id' --output text)
echo "CloudFront invalidation: $INVALIDATION_ID"

echo ""
for path in / /styles.css /common/auth-config.js /images/hydra24.jpg; do
    echo "  https://hydra24.co.za$path -> $(curl -s -o /dev/null -w '%{http_code} %{content_type}' "https://hydra24.co.za$path")"
done
echo "Done: https://hydra24.co.za"
